@realization_decorator(
    claim="v4-thm:realization-completeness-programme",
    source_volume="Vol IV",
    derived_from=[
        "Vol IV realization criterion manuscript proof",
        "Vol IV non-degenerate locus definition",
    ],
    verified_against=[
        "Finite predicate for Definition v4-def:realization-pair",
        "Vol IV registry import-time source-disjointness check",
    ],
    disjoint_rationale=(
        "The manuscript proof identifies Real(X,T) with the datum "
        "(d,e) of Definition v4-def:realization-pair.  The verification "
        "path uses a finite predicate for that definition and the "
        "registry's import-time disjointness check.  It does not use a "
        "case enumeration of Vols I--III claims, and it does not infer "
        "realization from membership in the non-degenerate locus."
    ),
)
def test_realization_completeness_programme():
    """The criterion accepts exactly complete realization pairs."""

    def is_realization_pair(pair):
        derived = {s.strip().lower() for s in pair["derived_from"]}
        verified = {s.strip().lower() for s in pair["verified_against"]}
        return (
            bool(pair["decorator"])
            and bool(pair["engine"])
            and bool(derived)
            and bool(verified)
            and derived.isdisjoint(verified)
            and pair["computed_value"] == pair["expected_value"]
        )

    realized_pair = {
        "decorator": "HZ-IV",
        "engine": "source-disjoint expected-value computation",
        "derived_from": ["manuscript proof"],
        "verified_against": ["comparison theorem"],
        "computed_value": ("Real", "d", "e"),
        "expected_value": ("Real", "d", "e"),
    }

    missing_engine = {
        **realized_pair,
        "engine": "",
    }
    tautological_pair = {
        **realized_pair,
        "verified_against": ["manuscript proof"],
    }
    mismatched_value = {
        **realized_pair,
        "expected_value": ("Real", "d", "e-prime"),
    }

    assert is_realization_pair(realized_pair)
    assert not is_realization_pair(missing_engine)
    assert not is_realization_pair(tautological_pair)
    assert not is_realization_pair(mismatched_value)

    # The Vol IV registry must include, at installation, the three
    # self-realized theorems of this chapter.
    expected_vol_iv_claims = {
        "v4-thm:realization-formalism-definition",
        "v4-thm:realization-existence-for-platonic-theorems",
        "v4-thm:realization-completeness-programme",
    }

    # The registry entries installed above must cover exactly these
    # three claims (plus whatever future Vol IV decorators have been
    # added, checked by subset).
    registered = realized_claims()
    for c in expected_vol_iv_claims:
        assert c in registered, (
            f"Vol IV claim {c!r} should be registered in the "
            "realization registry; missing suggests an import-time "
            "registration failure"
        )

    # Coverage snapshot shape: Vol IV source_volume entries count at
    # least the three native realization claims.
    from compute.lib.realization_registry import coverage_snapshot
    snapshot = coverage_snapshot()
    vol_iv_count = snapshot.get("Vol IV", 0)
    assert vol_iv_count >= 3, (
        f"Vol IV realization registry should have at least 3 "
        f"entries at installation; got {vol_iv_count}"
    )


